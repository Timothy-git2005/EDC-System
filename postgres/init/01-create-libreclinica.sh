#!/bin/bash
set -e 
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
    CREATE ROLE ${LIBCL_DB_USER} WITH LOGIN PASSWORD '${LIBCL_DB_PASSWORD}'
        NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT;
    
    CREATE DATABASE ${LIBCL_DB_NAME} OWNER ${LIBCL_DB_USER} ENCODING 'UTF8';
EOSQL